// Builds client/src/dm/dm-tw.css (1.14): the Tailwind classes the Chats screen uses, compiled with Tailwind 4.1.13
// (the version a Muse space builds the same screen with) and scoped to .dm-root. The rules only apply inside the Chats
// screen, so Cover Review's own styles stay exactly as they are, and the app needs no Tailwind to build or run.
//
// Run it after changing classes in client/src/dm: node scripts/dm-css.mjs
// It installs the pinned Tailwind command line into a temporary folder (network needed), and the smoke test fails
// when a class in client/src/dm has no rule in the file.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";

const TAILWIND = "4.1.13";
const ROOT = new URL("../", import.meta.url).pathname;
const DM = join(ROOT, "client", "src", "dm");
const OUT = join(DM, "dm-tw.css");

const work = mkdtempSync(join(tmpdir(), "dm-css-"));
try {
  writeFileSync(join(work, "package.json"), JSON.stringify({ name: "dm-css", private: true }));
  execFileSync("npm", ["install", "--no-audit", "--no-fund", "--silent", `tailwindcss@${TAILWIND}`, `@tailwindcss/cli@${TAILWIND}`, "postcss@8"], { cwd: work, stdio: "inherit" });
  writeFileSync(join(work, "in.css"), `@import "tailwindcss" source(none);\n@source "${DM}/*.jsx";\n`);
  execFileSync(join(work, "node_modules", ".bin", "tailwindcss"), ["-i", "in.css", "-o", "out.css"], { cwd: work, stdio: "inherit" });
  const postcss = createRequire(join(work, "package.json"))("postcss");
  const root = postcss.parse(readFileSync(join(work, "out.css"), "utf8"));

  // Unlayered, so Cover Review's element rules (button, input) can't outrank the Chats screen's classes.
  root.walkAtRules("layer", (at) => { if (at.nodes) at.replaceWith(at.nodes); else at.remove(); });
  // Keyframes get a dm- prefix, so they can never replace one of Cover Review's.
  const renamed = new Map();
  root.walkAtRules("keyframes", (at) => { renamed.set(at.params, `dm-${at.params}`); at.params = `dm-${at.params}`; });
  root.walkDecls(/^(animation(-name)?|--animate-.+)$/, (d) => {
    for (const [from, to] of renamed) d.value = d.value.replace(new RegExp(`(?<![-\\w])${from}(?![-\\w])`, "g"), to);
  });
  // Every rule applies only inside .dm-root. The page-level rules (html, :root, :host, body) land on .dm-root itself.
  const PAGE = new Set(["html", ":root", ":host", "body"]);
  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
    rule.selectors = [...new Set(rule.selectors.map((s) => (PAGE.has(s.trim()) ? ".dm-root" : `.dm-root ${s.trim()}`)))];
  });
  const header = `/* Generated by scripts/dm-css.mjs from client/src/dm with Tailwind ${TAILWIND}. Don't edit by hand: change the
   classes in client/src/dm, then run node scripts/dm-css.mjs. Every rule is scoped to .dm-root (the Chats screen). */\n`;
  writeFileSync(OUT, header + root.toString().replace(/\n{3,}/g, "\n\n").trim() + "\n");
  console.log(`wrote ${OUT}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
